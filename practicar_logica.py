def procesar_inventario(inventario, pedidos_hoy, productos_criticos):
  nuevo={
    "ventas_exitosas": 0,          # Cantidad de pedidos que sí se pudieron despachar
    "pedidos_rechazados": 0,       # Cantidad de pedidos rechazados por falta de stock
    "alertas_criticas": 0,         # Cuántas veces se compraron con éxito productos que están en el Set de críticos
    "inventario_final": {}         # El diccionario de inventario actualizado con el stock restante
}
  for i in pedidos_hoy:
    cliente=i["cliente"]
    producto=i["producto"]
    cantidad=i["cantidad"]
    if inventario[producto]["stock"]>=cantidad:
      inventario[producto]["stock"]-=cantidad
      nuevo["ventas_exitosas"]+=1
      if producto in productos_criticos:
        nuevo["alertas_criticas"]+=1
    else:
      nuevo["pedidos_rechazados"]+=1

  nuevo["inventario_final"]=inventario
  return nuevo
