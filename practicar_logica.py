def auditar_servidor(logs, baneados):
    # 1. Estructura base solicitada
    nuevo = {
        "total_intentos": 0,
        "bloqueados": 0,
        "usuarios_activos": {}  # Acá guardamos a los buenos
    }

    for f in logs:
        usuario = f["usuario"]
        accion = f["accion"]

        # El total de intentos cuenta cada registro que entra al servidor
        nuevo["total_intentos"] += 1

        # 2. Filtro con Set (O(1))
        if usuario in baneados:
            nuevo["bloqueados"] += 1
        else:
            # 3. Si el usuario no está baneado, lo registramos en usuarios_activos
            if usuario not in nuevo["usuarios_activos"]:
                nuevo["usuarios_activos"][usuario] = {"acciones": []}

            # Agregamos la acción a su lista personal
            nuevo["usuarios_activos"][usuario]["acciones"].append(accion)

    return nuevo

